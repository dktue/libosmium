#include <osmium/io/error.hpp>

#include <protozero/version.hpp>

#if PROTOZERO_VERSION_CODE >= 10600
# include <protozero/data_view.hpp>
#else
# include <protozero/types.hpp>
#endif

#include <zlib.h>

#include <cassert>
#include <limits>
#include <string>

namespace osmium {

    namespace io {

        namespace detail {

            constexpr int zlib_default_compression_level() noexcept {
                return Z_DEFAULT_COMPRESSION;
            }

            inline void zlib_check_compression_level(int value) {
                if (value < 0 || value > 9) {
                    throw std::invalid_argument{"The 'pbf_compression_level' for zlib compression must be between 0 and 9."};
                }
            }

            /**
             * Compress data using zlib.
             *
             * Note that this function can not compress data larger than
             * what fits in an unsigned long, on Windows this is usually 32bit.
             *
             * @param input Data to compress.
             * @param compression_level Compression level.
             * @returns Compressed data.
             */
            inline std::string zlib_compress(const std::string& input, int compression_level = Z_DEFAULT_COMPRESSION) {
                assert(input.size() < std::numeric_limits<unsigned long>::max());
                unsigned long output_size = ::compressBound(static_cast<unsigned long>(input.size())); // NOLINT(google-runtime-int)

                std::string output(output_size, '\0');

                const auto result = ::compress2(
                    reinterpret_cast<unsigned char*>(&*output.begin()),
                    &output_size,
                    reinterpret_cast<const unsigned char*>(input.data()),
                    static_cast<unsigned long>(input.size()), // NOLINT(google-runtime-int)
                    compression_level);

                if (result != Z_OK) {
                    throw io_error{std::string{"failed to compress data: "} + zError(result)};
                }

                output.resize(output_size);

                return output;
            }

            /**
             * Uncompress data using zlib.
             *
             * Note that this function can not uncompress data larger than
             * what fits in an unsigned long, on Windows this is usually 32bit.
             *
             * @param input Compressed input data.
             * @param raw_size Size of uncompressed data.
             * @param output Uncompressed result data.
             * @returns Pointer and size to incompressed data.
             */
            inline protozero::data_view zlib_uncompress_string(const char* input, unsigned long input_size, unsigned long raw_size, std::string& output) { // NOLINT(google-runtime-int)
                output.resize(raw_size);

                const auto result = ::uncompress(
                    reinterpret_cast<unsigned char*>(&*output.begin()),
                    &raw_size,
                    reinterpret_cast<const unsigned char*>(input),
                    input_size);

                if (result != Z_OK) {
                    throw io_error{std::string{"failed to uncompress data: "} + zError(result)};
                }

                return protozero::data_view{output.data(), output.size()};
            }

            /**
             * Uncompress only the beginning of some data using zlib.
             *
             * @param input Compressed input data.
             * @param input_size Size of compressed input data.
             * @param max_size Uncompress at most this many bytes.
             * @param output Uncompressed result data.
             * @returns Pointer and size to uncompressed data. The size is
             *          smaller than max_size only if all data was
             *          uncompressed.
             */
            inline protozero::data_view zlib_uncompress_prefix(const char* input, unsigned long input_size, unsigned long max_size, std::string& output) { // NOLINT(google-runtime-int)
                output.resize(max_size);

                z_stream stream{};
                stream.next_in = reinterpret_cast<unsigned char*>(const_cast<char*>(input)); // NOLINT(cppcoreguidelines-pro-type-const-cast) zlib API is not const-correct
                stream.avail_in = static_cast<unsigned int>(input_size);
                stream.next_out = reinterpret_cast<unsigned char*>(&*output.begin());
                stream.avail_out = static_cast<unsigned int>(max_size);

                auto result = ::inflateInit(&stream);
                if (result == Z_OK) {
                    result = ::inflate(&stream, Z_SYNC_FLUSH);
                    ::inflateEnd(&stream);
                    if (result == Z_OK && stream.avail_out != 0) {
                        result = Z_DATA_ERROR; // input ended before the end of the stream
                    }
                }

                if (result != Z_OK && result != Z_STREAM_END) {
                    throw io_error{std::string{"failed to uncompress data: "} + zError(result)};
                }

                output.resize(max_size - stream.avail_out);

                return protozero::data_view{output.data(), output.size()};
            }

        } // namespace detail

    } // namespace io

} // namespace osmium

